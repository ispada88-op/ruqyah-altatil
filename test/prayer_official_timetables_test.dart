void main() {
  group('official timetables vs app (±1 min)', () {
    for (final o in _official) {
      test(o.name, () {
        final method = PrayerMethod.byId(o.method)!;
        final worst = List<int>.filled(6, 0);
        for (final line in o.rows.trim().split('\n')) {
          final p = line.trim().split(RegExp(r'\s+'));
          final d = DateTime.parse(p[0]);
          final day = computePrayerDay(
              lat: o.lat, lon: o.lon, date: d, method: method, madhab: PrayerMadhab.shafi);
          for (var i = 0; i < 6; i++) {
            final t = day[_kinds[i]].toUtc().add(Duration(hours: o.tz));
            final hm = p[1 + i].split(':');
            final diff = t.hour * 60 + t.minute - (int.parse(hm[0]) * 60 + int.parse(hm[1]));
            if (diff.abs() > worst[i].abs()) worst[i] = diff;
          }
        }
        // ignore: avoid_print
        print('${o.name}: worst(app-official) F/S/D/A/M/I = ${worst.join(" ")}');
        for (var i = 0; i < 6; i++) {
          expect(worst[i].abs(), lessThanOrEqualTo(1), reason: '${o.name} ${_kinds[i].name}');
        }
      });
    }
  });

  test('cities use the verified official methods', () {
    String m(String city) => kPrayerCities.firstWhere((c) => c.name == city).method;
    expect(m('كوالالمبور'), 'jakim');
    expect(m('جاكرتا'), 'kemenag');
    expect(m('عمّان'), 'jordan');
    expect(m('إسطنبول'), 'turkey');
  });
}
