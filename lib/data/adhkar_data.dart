/// قائمة أذكار الصباح أو المساء بترتيب «حصن المسلم».
List<GeneralRuqyahItem> adhkarItems(AdhkarTime time) {
  final morning = time == AdhkarTime.morning;
  return [
    GeneralRuqyahItem(
      title: 'آية الكرسي',
      subtitle: 'البقرة (٢٥٥)',
      repeat: 1,
      isQuran: true,
      source: 'رواه الحاكم',
      blocks: [
        RuqyahBlock(
          heading: 'أَعُوذُ بِاللَّهِ مِنَ الشَّيْطَانِ الرَّجِيمِ',
          lines: verseLines(ayatAlKursi),
        ),
      ],
    ),
    GeneralRuqyahItem(
      title: 'المعوذات',
      subtitle: 'الإخلاص والفلق والناس',
      repeat: 3,
      isQuran: true,
      source: 'رواه أبو داود والترمذي',
      blocks: muawwidhatBlocks,
    ),
    for (final d in _adhkar)
      if ((morning ? d.morning : d.evening) != null)
        GeneralRuqyahItem(
          title: d.title,
          repeat: morning ? d.repeat : (d.eveningRepeat ?? d.repeat),
          source: morning ? d.source : (d.eveningSource ?? d.source),
          note: morning ? d.note : (d.eveningNote ?? d.note),
          blocks: [
            RuqyahBlock(lines: [(morning ? d.morning : d.evening)!]),
          ],
        ),
  ];
}
