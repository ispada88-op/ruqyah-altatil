class RulePoint {
  final String text;

  /// نص نبوي بلفظه (يُعرض بخط مميَّز) — اختياري.
  final String? hadith;

  /// المخرِّج: «رواه مسلم»، «متفق عليه»… (نسبة فقط، بلا حكم على السند).
  final String? source;
  const RulePoint(this.text, {this.hadith, this.source});
}

class RuleSection {
  final String title;
  final String icon; // مفتاح الأيقونة في الصفحة
  final List<RulePoint> points;
  const RuleSection(this.title, this.icon, this.points);
}

